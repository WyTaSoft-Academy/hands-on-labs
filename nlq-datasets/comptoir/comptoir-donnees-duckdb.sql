-- ---------------------------------------------------------------------
-- dim_date : un jour par ligne, du 1er janvier 2019 au 31 decembre 2026.
-- Generee plutot qu'inseree : 2 922 lignes.
-- ---------------------------------------------------------------------
CREATE OR REPLACE TABLE comptoir.dim_date (
  date_jour              DATE         NOT NULL,
  mois                   VARCHAR(7),              -- 2026-06
  libelle_mois           VARCHAR(20),             -- "juin 2026"
  trimestre              VARCHAR(7),              -- 2026-T2
  annee                  INTEGER,
  est_fin_de_mois        BOOLEAN,
  est_dernier_arrete     BOOLEAN                  -- repond a "au dernier arrete"
);

INSERT INTO comptoir.dim_date
SELECT
  d,
  YEAR(d) || '-' || LPAD(CAST(MONTH(d) AS VARCHAR), 2, '0'),
  CASE MONTH(d) WHEN 1 THEN 'janvier' WHEN 2 THEN 'février' WHEN 3 THEN 'mars'
                WHEN 4 THEN 'avril' WHEN 5 THEN 'mai' WHEN 6 THEN 'juin'
                WHEN 7 THEN 'juillet' WHEN 8 THEN 'août' WHEN 9 THEN 'septembre'
                WHEN 10 THEN 'octobre' WHEN 11 THEN 'novembre' WHEN 12 THEN 'décembre' END
    || ' ' || YEAR(d),
  YEAR(d) || '-T' || QUARTER(d),
  YEAR(d),
  d = LAST_DAY(d),
  d = (SELECT MAX(date_arrete) FROM comptoir.encours_credit_mensuel)
FROM (
  SELECT CAST(DATE '2019-01-01' + CAST(range AS INTEGER) AS DATE) AS d
  FROM range(2922)
) jours;
