-- =====================================================================
-- COMPTOIR rempli, pour DuckDB.
--
-- Les six tables du modele COMPTOIR de reference, sous leurs noms et
-- avec leurs commentaires, remplies des donnees de la meme banque
-- fictive que SOCLE (socle/socle-donnees-duckdb.sql) : les memes
-- credits, les memes clients, les memes operations, deja reformules.
-- Tables autonomes : SOCLE n'a pas besoin d'etre charge.
--
-- A utiliser APRES la restitution du TP 2 : la structure des tables est
-- celle du modele de reference, presente en restitution.
--
--   duckdb comptoir.duckdb -c ".read comptoir/comptoir-donnees-duckdb.sql"   (depuis nlq-datasets/)
--   duckdb -ui comptoir.duckdb        (interface, une fois la base creee)
--
-- Conventions : dernier arrete = 2026-09-30, « le mois dernier » =
-- septembre 2026. Les douze questions du TP 1 se posent sur ces tables :
-- a vous d'ecrire le SQL, avec les mesures certifiees du TP 2.
--
-- Deux choix de ce jeu de donnees, discutables :
--   segment : le code PE est traduit « Entreprise » (le seul client PE
--     est une SAS), et non « Patrimonial » ;
--   zone_commerciale : renseignee ici (Sud-Est, Ile-de-France) pour que
--     la colonne du modele ne soit pas vide ; SOCLE ne la porte pas.
--
-- Les six tables sont creees dans le schema comptoir. Pour les
-- interroger : USE comptoir;  puis  SELECT * FROM dim_client;
-- ou, sans USE :                     SELECT * FROM comptoir.dim_client;
-- Banque fictive, donnees inventees.
-- =====================================================================

